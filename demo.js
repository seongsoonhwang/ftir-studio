/* =========================================================================
 * demo.js — 데모용 **합성** 스펙트럼 (실측 데이터 아님)
 * 밴드 위치는 lib-bands.js의 문헌 대표값을 사용하고, 강도·폭은 시연용 임의값.
 * ========================================================================= */
(function () {
  'use strict';

  function rng(seed) {
    let s = seed >>> 0;
    return function () {
      s = (s * 1664525 + 1013904223) >>> 0;
      return s / 4294967296;
    };
  }

  const G = (x, c, w, a) => a * Math.exp(-0.5 * Math.pow((x - c) / w, 2));

  function build(peaks, opt) {
    const o = Object.assign({ seed: 1, noise: 0.0022, lo: 400, hi: 4000, step: 2, base: 0.03, slope: 0.02 }, opt || {});
    const r = rng(o.seed);
    const x = [], y = [];
    for (let v = o.lo; v <= o.hi; v += o.step) {
      let yy = o.base + o.slope * ((v - o.lo) / (o.hi - o.lo));
      for (const [c, w, a] of peaks) yy += G(v, c, w, a);
      yy += (r() - 0.5) * o.noise;
      x.push(v); y.push(Math.max(0.0005, yy));
    }
    return { x, y };
  }

  const PA6 = [
    [3300, 45, 0.60], [3060, 35, 0.08], [2930, 20, 0.34], [2860, 15, 0.20],
    [1640, 14, 1.05], [1540, 12, 0.78], [1463, 13, 0.32], [1415, 13, 0.24],
    [1370, 12, 0.22], [1265, 15, 0.46], [1200, 11, 0.34], [1120, 13, 0.16],
    [1020, 10, 0.10], [930, 13, 0.24], [690, 13, 0.32], [580, 12, 0.12]
  ];
  const PA66 = [
    [3300, 44, 0.58], [2930, 20, 0.30], [2860, 15, 0.17],
    [1640, 15, 1.00], [1540, 13, 0.86], [1463, 12, 0.36], [1410, 13, 0.26],
    [1370, 12, 0.19], [1270, 15, 0.42], [1200, 11, 0.32], [1130, 12, 0.14],
    [935, 13, 0.21], [690, 13, 0.30]
  ];
  const PPS = [
    [1573, 12, 0.72], [1470, 10, 0.46], [1388, 11, 0.52], [1090, 16, 0.52],
    [1015, 11, 0.36], [823, 9, 0.92], [745, 8, 0.22], [610, 10, 0.10]
  ];
  const PBT = [
    [1712, 17, 0.92], [1470, 11, 0.42], [1418, 11, 0.36], [1385, 10, 0.30],
    [1288, 13, 0.36], [1250, 11, 0.42], [1098, 13, 0.56], [1018, 10, 0.26],
    [918, 10, 0.32], [810, 10, 0.30], [730, 10, 0.22]
  ];
  const EPOXY = [
    [3420, 190, 0.38], [3050, 22, 0.18], [2925, 24, 0.26], [2870, 18, 0.14],
    [1610, 10, 0.50], [1510, 10, 0.88], [1455, 11, 0.30], [1382, 10, 0.26],
    [1295, 12, 0.30], [1245, 15, 0.62], [1184, 12, 0.46], [1037, 13, 0.56],
    [915, 10, 0.00], [830, 10, 0.52], [560, 14, 0.10]
  ];
  const NR = [
    [3030, 14, 0.12], [2925, 24, 0.92], [2855, 19, 0.58], [2720, 18, 0.10],
    [1663, 13, 0.42], [1450, 14, 0.52], [1375, 12, 0.36], [1300, 11, 0.14],
    [1128, 11, 0.12], [1030, 10, 0.10], [840, 10, 0.36]
  ];
  const NBR = [
    [2925, 24, 0.82], [2855, 18, 0.46], [2237, 10, 0.36], [1450, 13, 0.40],
    [1435, 11, 0.28], [970, 10, 0.20], [910, 10, 0.10]
  ];

  const clone = (arr) => arr.map((p) => p.slice());
  function with_(base, extra, opt) {
    const p = clone(base).concat(extra);
    return build(p, opt);
  }

  window.FTIR_DEMO = function () {
    const out = [];
    const push = (name, spec, note) => out.push({ name, x: spec.x, y: spec.y, note });

    // PA6: 초기 / 열노화 (카르보닐 + OH 증가)
    push('PA6 초기', build(PA6, { seed: 11 }), '합성');
    const aged = clone(PA6).concat([
      [1718, 26, 0.16], [1745, 14, 0.05], [3400, 120, 0.10], [1180, 30, 0.05]
    ]);
    push('PA6 열노화 168h', build(aged, { seed: 12 }), '합성');

    // PA6 + GF30 (Si–O 광범위 흡수, 수지 밴드 감쇠)
    const gf = clone(PA6).map((p) => [p[0], p[1], p[2] * 0.62]).concat([
      [1055, 70, 0.42], [800, 22, 0.14], [468, 26, 0.18]
    ]);
    push('PA6-GF30 정상품', build(gf, { seed: 13 }), '합성');

    // 사출 문제품: 수지 열화 + 이형제/스테아레이트 과다 가정
    const bad = clone(PA6).map((p) => [p[0], p[1], p[2] * 0.78]).concat([
      [1718, 24, 0.10], [1580, 12, 0.10], [1542, 11, 0.09], [1055, 70, 0.30], [800, 22, 0.10]
    ]);
    push('PA6-GF30 문제품', build(bad, { seed: 14 }), '합성');

    push('PA66', build(PA66, { seed: 21 }), '합성');
    push('PPS-GF40', with_(PPS, [[1100, 55, 0.30], [800, 20, 0.10]], { seed: 31 }), '합성');
    push('PBT', build(PBT, { seed: 41 }), '합성');

    // 에폭시: 미경화(915 존재) / 경화
    const uncured = clone(EPOXY).map((p) => (p[0] > 900 && p[0] < 930 ? [915, 10, 0.42] : p));
    push('에폭시 미경화', build(uncured, { seed: 51 }), '합성');
    push('에폭시 경화', build(EPOXY, { seed: 52 }), '합성');

    push('NR 초기', build(NR, { seed: 61 }), '합성');
    const nrAged = clone(NR).concat([[1715, 22, 0.22], [1180, 28, 0.08]]);
    push('NR 열노화', build(nrAged, { seed: 62 }), '합성');
    push('NBR', build(NBR, { seed: 71 }), '합성');

    return out;
  };
})();
